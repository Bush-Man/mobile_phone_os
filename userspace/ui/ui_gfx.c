/*
 * ui_gfx.c - surface pixel operations (phase 15, plan item 80).
 *
 * Draws into packed XRGB8888 surfaces (app windows are shm objects,
 * the compositor's stage is a private mmap). The 8x8 glyph table is
 * the kernel's phase-9 font, ported verbatim and extended with a
 * few punctuation marks the phone apps need; unknown characters
 * render as the same solid-box placeholder the kernel uses.
 */

#include "ui.h"

void ui_fill(struct ui_surface *s, u32 x, u32 y, u32 w, u32 h, u32 c)
{
    if (!s || !s->px)
        return;
    if (x >= s->w || y >= s->h)
        return;
    if (w > s->w - x)
        w = s->w - x;
    if (h > s->h - y)
        h = s->h - y;

    for (u32 r = 0; r < h; r++) {
        u32 *row = s->px + (u64)(y + r) * s->w + x;

        for (u32 i = 0; i < w; i++)
            row[i] = c;
    }
}

void ui_rect(struct ui_surface *s, u32 x, u32 y, u32 w, u32 h, u32 c)
{
    if (!s || !s->px || !w || !h)
        return;
    ui_fill(s, x, y, w, 1, c);          /* top                    */
    ui_fill(s, x, y + h - 1, w, 1, c);  /* bottom                 */
    ui_fill(s, x, y, 1, h, c);          /* left                   */
    ui_fill(s, x + w - 1, y, 1, h, c);  /* right                  */
}

u32 ui_text_w(const char *str)
{
    return strlen(str) * 8u;
}

