void ui_text(struct ui_surface *s, u32 x, u32 y, const char *str,
             u32 fg, u32 bg)
{
    u32 cx = x;

    if (!s || !s->px || !str)
        return;

    for (; *str; str++, cx += 8u) {
        const u8 *g;

        if ((unsigned char)*str < 96u &&
            (*str == ' ' || glyphs[(unsigned char)*str][0] ||
             glyphs[(unsigned char)*str][1] ||
             glyphs[(unsigned char)*str][7]))
            g = glyphs[(unsigned char)*str];
        else
            g = (const u8 *)"\xff\x81\x81\x81\x81\x81\x81\xff";

        for (u32 r = 0; r < 8u; r++) {
            u8 bits = g[r];

            for (u32 b = 0; b < 8u; b++) {
                u32 px = cx + b, py = y + r;
                u32 color;

                if (px >= s->w || py >= s->h)
                    continue;
                color = (bits & (0x80u >> b)) ? fg : bg;
                s->px[(u64)py * s->w + px] = color;
            }
        }
    }
}
